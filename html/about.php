<h2 id="about">
About
</h2>
<p>Old News aims to be an open-access repository for high-fidelity
transcriptions of important historical sources. We believe that plain
text transcriptions are the most valuable long-term data store because
plain text is easy to format and pleasing to read and reference.</p>
<h2 id="contributing">
Contributing
</h2>
<p>Contributions and text corrections are highly encouraged. You can
help by finding <a href="#typos">typos</a> and by <a
href="#article-contributions">contributing new sources</a>. If you spot
another kind of mistake feel free to e-mail
v.j.b.elgersma@students.uu.nl.</p>
<h3 id="typos">
Typos
</h3>
<p>If you find a typo or a mistake in our transcriptions, please make a
pull request on our article repository <a
href="https://github.com/victorelgersma/oldnews-article-repo">here</a>.</p>
<h3 id="article-contributions">
Article Contributions
</h3>
<p>If you would like to contribute a source yourself, feel free to use
<a href="https://github.com/victorelgersma/oldnews-OCR-pipeline">our OCR
pipeline</a> (MacOS + Linux only!), and submit your article as a pull
request in <a
href="https://github.com/victorelgersma/oldnews-article-repo">this
repo</a>. You are not obligated to use our pipeline; you may use any
method you like, but please provide the raw screenshots used in your
OCR, and a link (if applicable) to the original source.</p>
