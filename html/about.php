<h2 id="contributing">Contributing</h2>
<p>Contributions and text corrections are highly encouraged.</p>
<h3 id="typos">Typos</h3>
<p>If you find a typo in an article, feel free to make a pull request on
our article repository <a
href="https://github.com/victorelgersma/oldnews-article-repo">here</a>.</p>
<h3 id="article-contributions">Article Contributions</h3>
<p>If you would like to contribute an article yourself, feel free to use
<a href="https://github.com/victorelgersma/oldnews-OCR-pipeline">our OCR
pipeline</a> (MacOS + Linux only!), and submit your article as a pull
request in <a
href="https://github.com/victorelgersma/oldnews-article-repo">this
repo</a>. Please e-mail your screenshots to <a
href="mailto:v.j.b.elgersma@students.uu.nl">v.j.b.elgersma@students.uu.nl</a>.</p>
<p>If you would like to contribute but need a bit more technical support
than the above paragraph feel free to e-mail me at the address above and
I will happily on-board you into the process. Please note, however, that
I cannot help you if you are a Windows user.</p>
<h2 id="source-verification">Source Verification</h2>
<p>Every transcription hosted on this site maintains a direct link back
to its material reference point. By utilizing the <strong>‘View
Original’</strong> button on any given entry, you can immediately review
original photocopy clippings hosted by our image repository or visit
their permanent records.</p>
<h2 id="source-websites">Source Websites</h2>
<p>We are always adding new sources for our transcriptions. We are
currently sourcing articles from the following sources:</p>
<ul>
<li><a href="https://www.britishnewspaperarchive.co.uk/">The British
