<h2 id="about">
Why Old News?
</h2>
<p>Old News grew out of a dissatisfaction with the fact that most
historic journalism is only accessible through grainy scans on obscure
websites. We believe old news has a lot to teach historians, and we
therefore believe that historians have a lot to gain if old newspaper
articles are easy to read. The advent of free-to-use language models
like ChatGPT, Gemini, Claude, and DeepSeek has made automated
transcription a lot easier, which has made this sort of work much less
time consuming.</p>
<h2 id="contributing">
Contributing
</h2>
<p>Contributions and text corrections are highly encouraged. You can
help by finding <a href="#typos">typos</a> and by <a
href="#article-contributions">contributing new articles</a>. If you spot
another kind of mistake feel free to e-mail
v.j.b.elgersma@students.uu.nl.</p>
<h3 id="typos">
Typos
</h3>
<p>If you find a typo in an article, or you find that the text doesn’t
agree with the original scans, feel free to make a pull request on our
article repository <a
href="https://github.com/victorelgersma/oldnews-article-repo">here</a>.</p>
<h3 id="article-contributions">
Article Contributions
</h3>
<p>If you would like to contribute an article yourself, feel free to use
<a href="https://github.com/victorelgersma/oldnews-OCR-pipeline">our OCR
pipeline</a> (MacOS + Linux only!), and submit your article as a pull
request in <a
href="https://github.com/victorelgersma/oldnews-article-repo">this
repo</a>. Please e-mail the screenshots used for the OCR to <a
href="mailto:v.j.b.elgersma@students.uu.nl">v.j.b.elgersma@students.uu.nl</a>,
as well as a link to the original source.</p>
<p>If you would like to contribute but need a bit of technical
on-boarding feel free to e-mail me at the address above and I will try
to help out.</p>
<h2 id="source-verification">
Source Verification
</h2>
<p>Since we value traceability and want to guard against AI
hallucinations, we make sure each newspaper article has a link to an
original source, which hosts the original scans. By utilizing the
<strong>‘View Original’</strong> button on any given entry, you can
immediately review original photocopy clippings hosted by our image
repository or visit their permanent records. We do not accept articles
without a credible source.</p>
