<p><span class="newthought">Old News</span> is a curated digital
humanities archive focused on preserving and showcasing 19th-century
journalism. This platform offers clean transcriptions of fragile text
along with direct access to physical newspaper clippings, enabling
students and researchers to bridge raw primary prints with modern data
sets.</p>
<h2 id="open-source-pipeline">Open Source Pipeline</h2>
<p>The text displayed across this archive is generated using a custom
optical character recognition (OCR) pipeline built using <a
href="https://tesseractocr.org/" target="_blank"
rel="noopener noreferrer">Tesseract</a> and open-access AI tools.</p>
<p>The entire pipeline engine is open-source and public. You can view
the code, report issues, or study the infrastructure layout directly at
the <a href="https://github.com/victorelgersma/oldnews-OCR-pipeline"
target="_blank" rel="noopener noreferrer">oldnews-OCR-pipeline GitHub
Repository</a>. This repo also hosts the markdown texts appearing on
this site.</p>
